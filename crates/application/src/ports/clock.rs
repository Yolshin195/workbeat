use domain::UtcTimestamp;

/// Единственный порт, нужный use cases для работы со временем (для
/// тестируемости — реализация-фейк в `testing`, реализация-адаптер поверх
/// `chrono::Utc::now()` в Задаче 10). Никакого `Scheduler`/`JobId`/
/// `schedule_once`/`cancel` в системе нет: вместо "запланировать job и не
/// забыть отменить" вся проактивность реализована как периодический опрос
/// (poll), считающий `now() - started_at` по данным из БД (см. корневой
/// README.md, принцип таймеров). Сам цикл опроса (`tokio::time::interval`)
/// целиком живёт в адаптере (Задача 10) и просто вызывает use cases на
/// каждом тике — здесь никакого планировщика нет и не нужно.
pub trait Clock: Send + Sync {
    fn now(&self) -> UtcTimestamp;
}
