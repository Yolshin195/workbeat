//! Тонкий бинарь-обёртка над `app::run()` (composition root — см. `lib.rs`).
//! Единственное место в крейте, где ошибка запуска приводит к завершению
//! процесса — сама ошибка при этом типизированная (`app::RunError`), а не
//! паника, так что сообщение пользователю понятное (см. Задачу 13
//! корневого `tasks.md`: "падает с понятной ошибкой при отсутствии
//! обязательных переменных окружения").

#[tokio::main]
async fn main() {
    if let Err(err) = app::run().await {
        eprintln!("workbeat: не удалось запустить: {err}");
        std::process::exit(1);
    }
}
